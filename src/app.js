// The scope key is the uploadId generated by beginSshAgentUpload and kept only in
// state.sshAgentUploads until finishSshAgentUpload removes it. An AI cannot invent
// an id that has no matching live upload session, so approval cannot leak to another file.

function initialize() {
  const settings = readStoredSettings();
  initializeI18n(settings.uiLanguage);
  initializeAgentBridgeController({
    executeAgentCommand,
    startAgentOperation,
    runAgentOperation,
  });
  initializeResponseTest({ sendSerialPayload: sendPayload });
  initializeSerialRuntime({ updateConnectionUI });
  initializeSendHistory({ updateConnectionUI, updateNetworkUI });
  initializeNetworkRuntime({
    initializeSshBridge,
    toggleSshConnection,
    updateConnectionPresetControls,
  });
  initializeConnectionPresets({ updateConnectionUI });
  initializeAgentDeviceCommands({ updateConnectionUI, setWorkspaceMode });
  applySettings(settings);
  if (state.autoSaveEnabled && !state.autoSaveDirectoryHandle) {
    state.autoSaveEnabled = false;
  }
  configureBrowserNotice();
  bindEvents();
  renderAgentActivity();
  initializeTerminal({ sendSerialPayload: sendPayload });
  initializeSshTerminal();
  setSendPanelCollapsed(state.sendPanelCollapsed, { persist: false });
  setQuickSendCollapsed(state.quickSendCollapsed, { persist: false });
  setControlPanelGroup(state.controlPanelGroup, { persist: false });
  setMacroCollapsed(state.macroCollapsed, { persist: false });
  setNetworkQuickSendCollapsed(state.networkQuickSendCollapsed, { persist: false });
  setNetworkSendPanelCollapsed(state.networkSendPanelCollapsed, { persist: false });
  renderQuickCommandList("serial");
  renderQuickCommandList("network");
  renderMacroList();
  els.ymodemBlockSize.value = String(state.ymodemBlockSize);
  setYmodemMode(state.ymodemMode, { persist: false });
  setYmodemCollapsed(state.ymodemCollapsed, { persist: false });
  applyMobileLayoutDefaults();
  resetYmodemProgress();
  appendYmodemLog(t("ymodem.ready"), "info");
  setWorkspaceMode(state.workspaceMode, { persist: false });
  updateNetworkCounters();
  renderNetworkActivity(0, 0);
  renderNetworkPeerList();
  updateNetworkFollowUI();
  setConsoleView(state.consoleView, { focus: false, persist: false });
  updateReceiveModeUI();
  updateSendModeUI();
  updateTogglesUI();
  updateAutoSaveLimitUI();
  updateAutoSaveDialogUI();
  updateKeywordUI();
  applyKeywordStateToLogs();
  renderConnectionPresets("serial");
  renderConnectionPresets("network");
  renderSshPresets();
  renderSshQuickPaths();
  updateCounters();
  updateAutoSendUI();
  renderActivity(0, 0);
  updateFollowUI();
  updateConnectionUI();
  updateBridgeUI();
  if (state.networkProtocol === "ssh") initializeSshBridge();
  void refreshPorts().finally(() => {
    initializeAgentBridge();
    publishAgentState();
  });
  window.setInterval(() => {
    updateMetrics();
    updateNetworkMetrics();
    publishAgentState({ renderActivity: false });
  }, 250);
  window.setInterval(pruneAgentUploadApprovals, 60000);
}

initialize();
