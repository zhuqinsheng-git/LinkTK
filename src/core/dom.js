function createLucideIcon(name) {
  const icon = document.createElement("i");
  icon.dataset.lucide = name;
  icon.setAttribute("aria-hidden", "true");
  return icon;
}
function hasExternalTextEntryFocus() {
  const activeElement = document.activeElement;
  if (!activeElement || activeElement === document.body) return false;
  if (state.terminal?.element?.contains(activeElement)) return false;
  return activeElement.matches("input, textarea, select, [contenteditable='true']");
}
