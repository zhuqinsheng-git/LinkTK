function persistSettings() {
  const settings = {
    baudRate: Number(els.baudRate.value) || defaultSettings.baudRate,
    dataBits: els.dataBits.value,
    stopBits: els.stopBits.value,
    parity: els.parity.value,
    flowControl: els.flowControl.value,
    dtr: els.dtrToggle.checked,
    rts: els.rtsToggle.checked,
    lineEnding: els.lineEnding.value,
    receiveMode: state.receiveMode,
    sendMode: state.sendMode,
    showRx: state.showRx,
    showTx: state.showTx,
    showSys: state.showSys,
    timestamp: els.timestampToggle.checked,
    timestampMode: state.timestampMode,
    autoScroll: els.autoScrollToggle.checked,
    ansiColors: els.ansiToggle.checked,
    dualMode: state.dualMode,
    consoleView: state.consoleView,
    terminalLocalEcho: els.terminalLocalEcho.checked,
    sendPanelCollapsed: state.sendPanelCollapsed,
    quickSendCollapsed: state.quickSendCollapsed,
    controlPanelGroup: state.controlPanelGroup,
    serialQuickCommands: state.serialQuickCommands,
    serialSendHistory: state.serialSendHistory,
    serialConnectionPresets: state.serialConnectionPresets,
    templateCustomVariables: state.templateCustomVariables,
    responseExpected: state.responseExpected,
    responseTimeout: state.responseTimeout,
    responseCaseSensitive: state.responseCaseSensitive,
    autoSendCount: state.autoSendCount,
    macroCollapsed: state.macroCollapsed,
    macros: state.macros,
    ymodemMode: state.ymodemMode,
    ymodemBlockSize: state.ymodemBlockSize,
    ymodemCollapsed: state.ymodemCollapsed,
    workspaceMode: state.workspaceMode,
    networkProtocol: state.networkProtocol,
    networkRole: state.networkRole,
    networkHost: state.networkHost,
    networkPort: state.networkPort,
    sshAlias: state.sshAlias,
    sshHost: state.sshHost,
    sshPort: state.sshPort,
    sshUsername: state.sshUsername,
    sshSavePassword: state.sshSavePassword,
    sshPresets: state.sshPresets,
    networkReceiveMode: state.networkReceiveMode,
    networkSendMode: state.networkSendMode,
    networkShowRx: state.networkShowRx,
    networkShowTx: state.networkShowTx,
    networkShowSys: state.networkShowSys,
    networkTimestamp: state.networkTimestamp,
    networkTimestampMode: state.networkTimestampMode,
    networkAutoScroll: state.networkAutoScroll,
    networkDualMode: state.networkDualMode,
    keywordQuery: state.keywordQuery,
    keywordFilter: state.keywordFilter,
    keywordCaseSensitive: state.keywordCaseSensitive,
    keywordWholeWord: state.keywordWholeWord,
    networkSendPanelCollapsed: state.networkSendPanelCollapsed,
    networkQuickSendCollapsed: state.networkQuickSendCollapsed,
    networkQuickCommands: state.networkQuickCommands,
    networkSendHistory: state.networkSendHistory,
    networkAutoSendCount: state.networkAutoSendCount,
    autoSaveEnabled: state.autoSaveEnabled,
    autoSaveRotationMode: state.autoSaveRotationMode,
    autoSaveLimit: state.autoSaveLimit,
    autoSaveDirectoryName: state.autoSaveDirectoryName,
    networkConnectionPresets: state.networkConnectionPresets,
    deviceProfiles: state.deviceProfiles,
    activeDeviceProfileId: state.activeDeviceProfileId,
    taskTemplates: state.taskTemplates,
    bridgeSerialToNetwork: state.bridgeSerialToNetwork,
    bridgeNetworkToSerial: state.bridgeNetworkToSerial,
    agentApprovalMode: state.agentApprovalMode,
    uiLanguage: getLocale(),
  };

  try {
    localStorage.setItem(SETTINGS_KEY, JSON.stringify(settings));
  } catch {
    // Storage can be unavailable in hardened browser profiles.
  }
}

