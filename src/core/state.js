function readAgentSessionValue(key) {
  try {
    const existing = String(sessionStorage.getItem(key) || "").trim();
    if (existing) return existing;
    const value =
      key === AGENT_SESSION_ID_KEY
        ? crypto.randomUUID?.() || `ui-${Date.now()}-${Math.random().toString(16).slice(2)}`
        : "";
    if (value) sessionStorage.setItem(key, value);
    return value;
  } catch {
    return key === AGENT_SESSION_ID_KEY
      ? crypto.randomUUID?.() || `ui-${Date.now()}-${Math.random().toString(16).slice(2)}`
      : "";
  }
}

function persistAgentSessionLabel(value) {
  state.agentSessionLabel = String(value || "").trim().slice(0, 120);
  try {
    if (state.agentSessionLabel) {
      sessionStorage.setItem(AGENT_SESSION_LABEL_KEY, state.agentSessionLabel);
    } else {
      sessionStorage.removeItem(AGENT_SESSION_LABEL_KEY);
    }
  } catch {
    // Session storage can be unavailable in hardened browser profiles.
  }
}

export { persistAgentSessionLabel, readAgentSessionValue, state };
